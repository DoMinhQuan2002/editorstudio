-- =====================================================================
-- Media Studio — database design v1
-- Two databases:
--   A. SERVER (PostgreSQL 15+): accounts, login, OTP, plans, payments,
--      template catalog, template audio.
--   B. LOCAL (SQLite, one file per user on their machine, CapCut-style):
--      projects, imported media, edit revisions, exports.
-- Server never stores the user's photos/videos.
-- =====================================================================


-- #####################################################################
-- A. SERVER DATABASE (PostgreSQL)
-- #####################################################################
CREATE EXTENSION IF NOT EXISTS pgcrypto;   -- gen_random_uuid()
CREATE EXTENSION IF NOT EXISTS citext;     -- case-insensitive email

-- ---------- 1. Accounts & login ------------------------------------
CREATE TABLE users (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    email           CITEXT NOT NULL UNIQUE,
    email_verified  BOOLEAN NOT NULL DEFAULT FALSE,
    password_hash   TEXT,                       -- NULL if user only uses Google/Facebook
    display_name    VARCHAR(120),
    avatar_url      TEXT,
    locale          VARCHAR(10) NOT NULL DEFAULT 'vi',
    status          VARCHAR(20) NOT NULL DEFAULT 'active'
                    CHECK (status IN ('pending','active','locked','deleted')),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_login_at   TIMESTAMPTZ,
    deleted_at      TIMESTAMPTZ
);

-- One user can link several login methods (email+password, Google, Facebook).
CREATE TABLE user_identities (
    id                UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id           UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    provider          VARCHAR(20) NOT NULL CHECK (provider IN ('email','google','facebook')),
    provider_user_id  VARCHAR(255) NOT NULL,     -- Google "sub", Facebook id, or the email
    provider_email    CITEXT,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_used_at      TIMESTAMPTZ,
    UNIQUE (provider, provider_user_id),
    UNIQUE (user_id, provider)
);

-- OTP codes sent by email (sign-up, login without password, password reset).
CREATE TABLE email_otps (
    id            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    email         CITEXT NOT NULL,
    user_id       UUID REFERENCES users(id) ON DELETE CASCADE,   -- NULL before sign-up completes
    purpose       VARCHAR(20) NOT NULL CHECK (purpose IN ('signup','login','reset_password','change_email')),
    code_hash     TEXT NOT NULL,                 -- never store the plain 6-digit code
    attempts      SMALLINT NOT NULL DEFAULT 0,   -- lock after e.g. 5 wrong tries
    expires_at    TIMESTAMPTZ NOT NULL,          -- e.g. now() + 5 minutes
    consumed_at   TIMESTAMPTZ,
    request_ip    INET,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_email_otps_lookup ON email_otps (email, purpose, created_at DESC);

-- Desktop installs (limit how many machines one account uses).
CREATE TABLE devices (
    id            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id       UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    device_key    VARCHAR(128) NOT NULL,         -- stable id generated by the app
    device_name   VARCHAR(120),
    os            VARCHAR(60),
    app_version   VARCHAR(20),
    first_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_seen_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    revoked_at    TIMESTAMPTZ,                   -- set when another machine signs in
    revoke_reason VARCHAR(30),                   -- 'signed_in_elsewhere','logout','admin'
    UNIQUE (user_id, device_key)
);
-- RULE: one account = one machine. Only one non-revoked device per user.
-- On login from machine 2 (same transaction):
--   1. UPDATE devices SET revoked_at = now(), revoke_reason = 'signed_in_elsewhere'
--        WHERE user_id = $1 AND revoked_at IS NULL AND device_key <> $2;
--   2. UPDATE refresh_tokens SET revoked_at = now()
--        WHERE user_id = $1 AND revoked_at IS NULL;
--   3. Insert/re-activate machine 2 and issue new tokens.
-- Machine 1's next API call (or token refresh) gets 401 'signed_in_elsewhere'
-- and the app shows "Tài khoản đã đăng nhập trên máy khác" then logs out.
CREATE UNIQUE INDEX ux_devices_one_active ON devices (user_id) WHERE revoked_at IS NULL;

-- Refresh tokens (access token is a short-lived JWT, not stored).
CREATE TABLE refresh_tokens (
    id            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id       UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    device_id     UUID REFERENCES devices(id) ON DELETE CASCADE,
    token_hash    TEXT NOT NULL UNIQUE,
    expires_at    TIMESTAMPTZ NOT NULL,
    revoked_at    TIMESTAMPTZ,
    replaced_by   UUID REFERENCES refresh_tokens(id),   -- rotation chain
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_refresh_tokens_user ON refresh_tokens (user_id);

-- ---------- 2. Plans, prices, features -------------------------------
CREATE TABLE plans (
    id            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    code          VARCHAR(40) NOT NULL UNIQUE,   -- 'free', 'pro'
    name          VARCHAR(80) NOT NULL,
    description   TEXT,
    is_active     BOOLEAN NOT NULL DEFAULT TRUE,
    sort_order    INT NOT NULL DEFAULT 0,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Each plan is sold per week / month / year.
CREATE TABLE plan_prices (
    id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    plan_id        UUID NOT NULL REFERENCES plans(id) ON DELETE CASCADE,
    billing_period VARCHAR(10) NOT NULL CHECK (billing_period IN ('week','month','year')),
    amount         NUMERIC(12,2) NOT NULL CHECK (amount >= 0),
    currency       CHAR(3) NOT NULL DEFAULT 'VND',
    is_active      BOOLEAN NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (plan_id, billing_period, currency, is_active)
);

-- What a plan unlocks; checked by code, so new features need no schema change.
CREATE TABLE features (
    code          VARCHAR(60) PRIMARY KEY,       -- see seed data at the end
    name          VARCHAR(120) NOT NULL,
    description   TEXT
);

CREATE TABLE plan_features (
    plan_id       UUID NOT NULL REFERENCES plans(id) ON DELETE CASCADE,
    feature_code  VARCHAR(60) NOT NULL REFERENCES features(code),
    limit_value   INT,                           -- NULL = unlimited, e.g. exports per day
    PRIMARY KEY (plan_id, feature_code)
);

-- ---------- 3. Subscriptions & payments -----------------------------
CREATE TABLE subscriptions (
    id                   UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id              UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    plan_price_id        UUID NOT NULL REFERENCES plan_prices(id),
    status               VARCHAR(20) NOT NULL
                         CHECK (status IN ('pending','active','expired','canceled')),  -- no free trial
    current_period_start TIMESTAMPTZ NOT NULL,
    current_period_end   TIMESTAMPTZ NOT NULL,
    -- VNPay pays once per period (no automatic card renewal), so the user
    -- buys again when the period ends; the app reminds them a few days before.
    canceled_at          TIMESTAMPTZ,
    renewal_reminded_at  TIMESTAMPTZ,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_subscriptions_user ON subscriptions (user_id, status, current_period_end DESC);
-- At most one live subscription per user.
CREATE UNIQUE INDEX ux_subscriptions_one_live ON subscriptions (user_id)
    WHERE status = 'active';
-- Buying again while active: extend current_period_end instead of a second row.

CREATE TABLE payments (
    id                 UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id            UUID NOT NULL REFERENCES users(id),
    subscription_id    UUID REFERENCES subscriptions(id),
    plan_price_id      UUID NOT NULL REFERENCES plan_prices(id),
    amount             NUMERIC(12,2) NOT NULL,
    currency           CHAR(3) NOT NULL,
    status             VARCHAR(20) NOT NULL CHECK (status IN ('pending','succeeded','failed','canceled','refunded')),
    -- VNPay fields
    vnp_txn_ref        VARCHAR(100) NOT NULL UNIQUE,   -- our order code sent as vnp_TxnRef
    vnp_transaction_no VARCHAR(50),                    -- VNPay's vnp_TransactionNo
    vnp_response_code  VARCHAR(5),                     -- '00' = success
    vnp_bank_code      VARCHAR(20),
    vnp_card_type      VARCHAR(20),
    vnp_pay_date       VARCHAR(14),                    -- yyyyMMddHHmmss as returned
    ipn_received_at    TIMESTAMPTZ,                    -- only the IPN (server call) activates the plan
    paid_at            TIMESTAMPTZ,
    raw_payload        JSONB,                          -- IPN query for audits (checksum verified)
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_payments_user ON payments (user_id, created_at DESC);

-- ---------- 4. Template catalog -------------------------------------
CREATE TABLE template_categories (
    id            SERIAL PRIMARY KEY,
    code          VARCHAR(40) NOT NULL UNIQUE,   -- 'story','carousel','cut_out','travel','trending'
    name          VARCHAR(80) NOT NULL,
    icon          VARCHAR(40),
    sort_order    INT NOT NULL DEFAULT 0
);

-- Aspect ratios as data, so 1:1, 4:5, 16:9 can be added later.
CREATE TABLE aspect_ratios (
    code          VARCHAR(10) PRIMARY KEY,       -- '9:16'
    width         INT NOT NULL,                  -- default canvas, e.g. 1080
    height        INT NOT NULL                   -- e.g. 1920
);

-- Background music / sound for templates (one default per template, can be shared).
CREATE TABLE audio_tracks (
    id            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    title         VARCHAR(160) NOT NULL,
    artist        VARCHAR(160),
    duration_ms   INT NOT NULL,
    file_url      TEXT NOT NULL,
    file_sha256   CHAR(64) NOT NULL,
    bpm           NUMERIC(6,2),
    beat_markers  JSONB,                         -- [ms, ms, ...] for syncing scene cuts
    license       VARCHAR(40) NOT NULL,          -- 'owned','royalty_free','licensed'
    license_note  TEXT,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE templates (
    id            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    slug          VARCHAR(80) NOT NULL UNIQUE,   -- 'fall-diary','november-dump'
    name          VARCHAR(120) NOT NULL,
    description   TEXT,
    category_id   INT REFERENCES template_categories(id),
    output_kind   VARCHAR(10) NOT NULL CHECK (output_kind IN ('video','image')),  -- Fall Diary = video, November = image
    is_premium    BOOLEAN NOT NULL DEFAULT FALSE,  -- free users: open + edit up to step 6, export blocked
    status        VARCHAR(20) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','published','retired')),
    sort_order    INT NOT NULL DEFAULT 0,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Each change to a template's layout is a new version; projects remember which version they used.
CREATE TABLE template_versions (
    id               UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    template_id      UUID NOT NULL REFERENCES templates(id) ON DELETE CASCADE,
    version          VARCHAR(40) NOT NULL,       -- '0.9.0-reference-overlays'
    definition       JSONB NOT NULL,             -- groups, slots, timings, effects, stickers
    min_app_version  VARCHAR(20),
    default_audio_id UUID REFERENCES audio_tracks(id),   -- NULL until audio is made
    duration_ms      INT,                        -- video templates
    page_count       INT,                        -- image templates (November = 7)
    min_media        INT NOT NULL DEFAULT 1,
    max_media        INT NOT NULL,               -- Fall Diary 36, November 13
    is_current       BOOLEAN NOT NULL DEFAULT FALSE,
    published_at     TIMESTAMPTZ,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (template_id, version)
);
CREATE UNIQUE INDEX ux_template_versions_current ON template_versions (template_id) WHERE is_current;

-- Which aspect ratios a template version supports (only 9:16 today).
CREATE TABLE template_version_aspects (
    template_version_id UUID NOT NULL REFERENCES template_versions(id) ON DELETE CASCADE,
    aspect_code         VARCHAR(10) NOT NULL REFERENCES aspect_ratios(code),
    canvas_width        INT NOT NULL,
    canvas_height       INT NOT NULL,
    layout_override     JSONB,                   -- per-ratio position changes
    is_default          BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (template_version_id, aspect_code)
);

-- Downloadable files: poster, demo video, fonts, stickers, emoji PNGs, title art.
CREATE TABLE template_assets (
    id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    template_version_id UUID NOT NULL REFERENCES template_versions(id) ON DELETE CASCADE,
    kind                VARCHAR(20) NOT NULL CHECK (kind IN ('poster','preview_video','font','sticker','overlay','other')),
    aspect_code         VARCHAR(10) REFERENCES aspect_ratios(code),  -- NULL = all ratios
    file_url            TEXT NOT NULL,
    file_sha256         CHAR(64) NOT NULL,
    byte_size           BIGINT NOT NULL
);

-- Usage counters (no user media): which templates are opened/exported.
CREATE TABLE usage_events (
    id            BIGSERIAL PRIMARY KEY,
    user_id       UUID REFERENCES users(id) ON DELETE SET NULL,
    device_id     UUID REFERENCES devices(id) ON DELETE SET NULL,
    event         VARCHAR(40) NOT NULL,          -- 'template_open','export_done'
    template_id   UUID REFERENCES templates(id),
    meta          JSONB,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_usage_events_user_day ON usage_events (user_id, event, created_at);


-- ---------- 5. Seed data: plans & access rules ---------------------
-- Free (no plan): every template can be used through step 6 (choose media,
-- process, edit, export settings). Exporting a premium template opens the
-- plan picker. Free templates export normally.
INSERT INTO features (code, name) VALUES
  ('export_free_templates',    'Xuất video/ảnh từ mẫu miễn phí'),
  ('export_premium_templates', 'Xuất video/ảnh từ mẫu trả phí');

INSERT INTO plans (code, name, sort_order) VALUES ('free','Miễn phí',0), ('pro','Pro',1);

INSERT INTO plan_features (plan_id, feature_code)
SELECT id, 'export_free_templates' FROM plans WHERE code IN ('free','pro');
INSERT INTO plan_features (plan_id, feature_code)
SELECT id, 'export_premium_templates' FROM plans WHERE code = 'pro';

-- Prices are placeholders; set the real amounts.
INSERT INTO plan_prices (plan_id, billing_period, amount, currency)
SELECT id, p.period, p.amount, 'VND' FROM plans,
  (VALUES ('week', 0), ('month', 0), ('year', 0)) AS p(period, amount)
WHERE code = 'pro';

-- Export check (server, called before an export starts):
--   template.is_premium = FALSE  -> allowed
--   template.is_premium = TRUE   -> allowed only if the user has a subscription with
--        status = 'active' AND current_period_end > now()
--   otherwise -> 402 'plan_required' and the app shows the plan picker.


-- #####################################################################
-- B. LOCAL DATABASE (SQLite, on the user's machine)
--    e.g. %LOCALAPPDATA%\MediaStudio\<user_id>\library.db
--    Project files live in  ...\Projects\<project_id>\
-- #####################################################################

-- Cached copy of the signed-in user and plan so the app works offline for a while.
CREATE TABLE local_account (
    user_id            TEXT PRIMARY KEY,
    email              TEXT NOT NULL,
    display_name       TEXT,
    plan_code          TEXT NOT NULL DEFAULT 'free',
    features_json      TEXT NOT NULL DEFAULT '[]',   -- unlocked feature codes
    entitlement_until  TEXT,                          -- ISO time; re-check online after this
    last_synced_at     TEXT
);

-- Template definitions downloaded from the server.
CREATE TABLE cached_templates (
    template_version_id TEXT PRIMARY KEY,
    template_slug       TEXT NOT NULL,
    version             TEXT NOT NULL,
    output_kind         TEXT NOT NULL CHECK (output_kind IN ('video','image')),
    definition_json     TEXT NOT NULL,
    local_folder        TEXT NOT NULL,
    downloaded_at       TEXT NOT NULL
);

CREATE TABLE projects (
    id                  TEXT PRIMARY KEY,                 -- UUID
    name                TEXT NOT NULL,
    template_slug       TEXT NOT NULL,
    template_version_id TEXT NOT NULL,
    output_kind         TEXT NOT NULL CHECK (output_kind IN ('video','image')),
    aspect_code         TEXT NOT NULL DEFAULT '9:16',
    canvas_width        INTEGER NOT NULL,
    canvas_height       INTEGER NOT NULL,
    audio_track_id      TEXT,                             -- template default or user choice
    audio_volume        REAL NOT NULL DEFAULT 1.0,
    audio_muted         INTEGER NOT NULL DEFAULT 0,
    status              TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','processing','ready','exported')),
    folder_path         TEXT NOT NULL,
    cover_path          TEXT,
    current_revision    INTEGER NOT NULL DEFAULT 0,
    duration_ms         INTEGER,
    created_at          TEXT NOT NULL,
    updated_at          TEXT NOT NULL,
    opened_at           TEXT,
    deleted_at          TEXT                              -- soft delete (recycle bin)
);
CREATE INDEX ix_projects_recent ON projects (deleted_at, opened_at DESC);

-- Photos/videos the user picked, in order, and where each landed in the template.
CREATE TABLE project_media (
    id                TEXT PRIMARY KEY,
    project_id        TEXT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    order_index       INTEGER NOT NULL,                   -- 1..36
    kind              TEXT NOT NULL CHECK (kind IN ('image','video')),
    source_path       TEXT NOT NULL,                      -- original file on disk
    copied_path       TEXT,                               -- copy inside project folder
    file_sha256       TEXT,
    width             INTEGER,
    height            INTEGER,
    duration_ms       INTEGER,
    byte_size         INTEGER,
    slot_role         TEXT,                               -- 'background','overlay','page_photo'
    slot_group        INTEGER,                            -- Fall Diary group 1..4
    slot_page         INTEGER,                            -- November page 1..7
    cutout_path       TEXT,                               -- background-removed PNG
    user_scale        REAL NOT NULL DEFAULT 1.0,          -- step-5 manual edits
    user_offset_x     REAL NOT NULL DEFAULT 0.0,
    user_offset_y     REAL NOT NULL DEFAULT 0.0,
    UNIQUE (project_id, order_index)
);

-- Each save of the edited composition (undo history / recovery).
CREATE TABLE project_revisions (
    project_id        TEXT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    revision          INTEGER NOT NULL,
    composition_json  TEXT NOT NULL,                      -- Project V2 / composition graph
    note              TEXT,
    created_at        TEXT NOT NULL,
    PRIMARY KEY (project_id, revision)
);

-- Text and sticker layers the user changes.
CREATE TABLE project_layers (
    id             TEXT PRIMARY KEY,
    project_id     TEXT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    kind           TEXT NOT NULL CHECK (kind IN ('text','sticker')),
    page_or_scene  INTEGER,
    content        TEXT,
    style_json     TEXT,
    start_ms       INTEGER,
    end_ms         INTEGER,
    z_index        INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE exports (
    id             TEXT PRIMARY KEY,
    project_id     TEXT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    revision       INTEGER NOT NULL,
    output_kind    TEXT NOT NULL CHECK (output_kind IN ('video','image')),
    format         TEXT NOT NULL,                         -- 'mp4','png','jpg','zip'
    quality        TEXT NOT NULL,                         -- 'standard','high'
    width          INTEGER NOT NULL,
    height         INTEGER NOT NULL,
    fps            REAL,
    output_path    TEXT,
    byte_size      INTEGER,
    status         TEXT NOT NULL CHECK (status IN ('queued','running','succeeded','failed','canceled')),
    error_message  TEXT,
    started_at     TEXT,
    finished_at    TEXT
);
CREATE INDEX ix_exports_project ON exports (project_id, started_at DESC);

CREATE TABLE app_settings (
    key    TEXT PRIMARY KEY,                              -- 'export_folder','language','gpu'
    value  TEXT NOT NULL
);
